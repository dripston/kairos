#!/usr/bin/env python3
"""Regenerate film/SCRIPT.md from the Neha VO timeline and the shot list.

    python3 film/tools/shotlist.py && python3 film/tools/make_script.py
"""
from __future__ import annotations

import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FILM = os.path.join(HERE, "..")


def mmss(t):
    return f"{int(t // 60)}:{t % 60:04.1f}"


def main():
    tl = json.load(open(os.path.join(FILM, "audio", "vo_neha", "timeline.json"), encoding="utf-8"))
    lines = json.load(open(os.path.join(FILM, "audio", "vo_neha", "lines.json"), encoding="utf-8"))
    shots = list(csv.DictReader(open(os.path.join(FILM, "shot-list.csv"), encoding="utf-8")))
    m = tl["markers"]
    out = ["# Kairos film: script (generated)\n",
           "Generated by `python3 film/tools/make_script.py` from `audio/vo_neha/timeline.json` and `shot-list.csv`.\n",
           f"**Runtime:** {mmss(tl['runtime_s'])} ({tl['runtime_s']:g} s). **Voice:** Neha only (Sarvam bulbul:v3, pace 1.2, AI-generated). "
           "**Music:** one line, `MUSIC_SRC` in `kairos_film.html` (default `music/original/v3_cinematic_trailer.m4a`), ducked 11 dB under "
           "every line. **Captions:** on by default, the exact VO text.\n",
           "**Aladdin = Kairos Supervisor (K06):** the safety gate that checks every message against the lender's rules when planning "
           "and again just before sending. All borrowers are synthetic; every number is SIMULATED (sources: `TRUTH_TABLE.md`).\n",
           f"Markers: lift {m['lift_meet_kairos']:.2f} s (\"Meet Kairos\"), climax {m['climax_proof']:.2f} s (proof), final line {m['final_line']:.2f} s.\n"]
    for i, (ln, sh) in enumerate(zip(tl["lines"], shots), 1):
        out.append(f"## {i}. {sh['shot_id']} · {mmss(float(sh['start_s']))} to {mmss(float(sh['end_s']))}\n")
        out.append(f"**Neha** ({mmss(ln['start'])} to {mmss(ln['end'])}): {lines[ln['line']]['text']}\n")
        if ln["line"] == "11_agent_hi":
            out.append("English caption: \"Hello! Your EMI is due tomorrow. Shall I send you the payment link?\"\n")
        out.append(f"**On screen:** {sh['on_screen_text'] or '(footage only)'}\n")
        out.append(f"**Visual proof:** {sh['visual_action']}. ({sh['method']})\n")
        out.append(f"**Sound / cut:** {sh['sound']}; {sh['transition']}.\n")
    open(os.path.join(FILM, "SCRIPT.md"), "w", encoding="utf-8").write("\n".join(out))
    print("wrote film/SCRIPT.md")


if __name__ == "__main__":
    main()
