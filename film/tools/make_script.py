def mmss(t):
    return f"{int(t // 60)}:{t % 60:04.1f}"


def section(cut):
    scenes, cuts, _ = compose.parse_film(compose.FILM)
    tl, total = compose.timeline(scenes, cuts[cut], cut)
    out = [f"## {'Full film' if cut == 'full' else 'Operator cut (`?cut=operator`)'}: {int(total // 60)}:{int(total % 60):02d} ({total:g} s)\n"]
    words = 0
    for i, s in enumerate(tl, 1):
        shots = shotlist.SHOTS[s["id"]]
        out.append(f"### {i}. {s['id']} · {mmss(s['start'])} to {mmss(s['end'])} ({s['dur']:g} s)\n")
        out.append("**Voice-over and character lines** (time from film start · speaker · voice):\n")
        for c in s["cues"]:
            v, _ = compose.VOICES.get(c["speaker"], compose.VOICES[None])
            who = compose.SPEAKER_NAME.get(c["speaker"], "Narrator")
            out.append(f"- `{mmss(s['start'] + c['t'])}` **{who}** ({v}): {c['caption']}")
            words += len(c["caption"].split())
        out.append("")
        out.append("**On screen:** " + " · ".join(sh[6] for sh in shots if sh[6]) + "\n")
        out.append("**Visual:** " + " Then: ".join(sh[2] + "." for sh in shots) + "\n")
        out.append(f"**Real product screen:** {RECORD.get(s['id'], '')}\n")
    out.append(f"Words spoken: about {words} in {total:g} s.\n")
    return "\n".join(out)


